import assert from 'node:assert/strict';
import {blankWorkspace,normalizeWorkspace,addSignal} from '../lib/model.ts';
import {applyLearningRequest,consentedSignals,hasLearningConsent} from '../lib/learning.ts';
import {companies,sampleProfile} from '../lib/catalog.ts';
import {evaluateMatch} from '../lib/matching.ts';
const now=new Date().toISOString(),before=new Date(Date.now()-60_000).toISOString();
const blank=blankWorkspace();
assert.equal(blank.settings.learning,false);
assert.equal(normalizeWorkspace({...blank,settings:{...blank.settings,learning:true}}).settings.learning,false,'old default-on is not consent');
assert.equal((addSignal(blank,'x','view').signals||[]).length,0);
const spoof={...blank,settings:{...blank.settings,learning:true,learningConsent:{version:1,grantedAt:before}}};
assert.equal(hasLearningConsent(applyLearningRequest(spoof,blank,now)),false,'state PUT cannot forge a consent timestamp');
const legacySignal={id:'old',entityId:companies[0].id,kind:'interest',time:before};
const old={...blank,profile:sampleProfile('investor'),saved:[companies[0].id],interested:[companies[0].id],signals:[legacySignal]};
const granted=applyLearningRequest({...old,settings:{...old.settings,learningRequest:'grant'}},old,now);
assert.equal(hasLearningConsent(granted),true);
assert.equal(granted.settings.learningConsent.grantedAt,now);
assert.equal(granted.settings.learningRequest,undefined);
assert.deepEqual(consentedSignals(granted),[],'grant does not retroactively use old events');
assert.equal(evaluateMatch(companies[0],granted,'investor').feedbackAdjustment,0,'old saved/interest arrays are not an implicit learning input');
const active=addSignal(granted,companies[0].id,'interest');
assert.equal(consentedSignals(active).length,1);
assert.ok(evaluateMatch(companies[0],active,'investor').feedbackAdjustment>0);
const revoked=applyLearningRequest({...active,settings:{...active.settings,learningRequest:'revoke'}},active,now);
assert.equal(hasLearningConsent(revoked),false);
assert.equal(evaluateMatch(companies[0],revoked,'investor').feedbackAdjustment,0);
assert.equal(addSignal(revoked,'x','view').signals.length,active.signals.length);
const cleared=applyLearningRequest({...active,settings:{...active.settings,learningRequest:'clear'}},active,now);
assert.deepEqual(cleared.signals,[]);assert.deepEqual(cleared.saved,active.saved);assert.equal(hasLearningConsent(cleared),false);
assert.throws(()=>applyLearningRequest({...blank,settings:{...blank.settings,learningRequest:'yes'}},blank),/授权/);
assert.equal(normalizeWorkspace({}).settings.learning,false);
console.log('PASS: explicit consent, legacy migration, server stamps, revoke, clear, and no retroactive ranking');
