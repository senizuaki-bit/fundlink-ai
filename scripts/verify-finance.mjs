import assert from 'node:assert/strict';
import {calculateScenario,calculateCapTable,diagnoseCapital,diligenceFramework} from '../lib/finance.ts';
const input={cash:300,burn:50,months:18,buffer:100,pre:7000,raise:3000,revenue:1200,cost:400,entry:1000,exit:2500};
const result=calculateScenario(input);
assert.equal(result.runway,6);assert.equal(result.fundingNeed,700);assert.equal(result.postMoney,10000);
assert.equal(result.dilution,.3);assert.equal(result.existingOwnership,.7);assert.equal(result.grossMargin,2/3);assert.equal(result.moic,2.5);
assert.equal(calculateScenario({...input,cash:5000}).fundingNeed,0);
assert.equal(calculateScenario({...input,burn:0}).runway,null);
assert.equal(calculateScenario({...input,revenue:0}).grossMargin,null);
assert.equal(calculateScenario({...input,entry:0}).moic,null);
assert.equal(calculateScenario({...input,pre:0,raise:0}).dilution,null);
assert.equal(calculateScenario({...input,revenue:100,cost:200}).grossMargin,-1);
assert.throws(()=>calculateScenario({...input,burn:-1}),/有限数值/);
assert.throws(()=>calculateScenario({...input,cash:NaN}),/有限数值/);
assert.throws(()=>calculateScenario({...input,raise:Infinity}),/有限数值/);
assert.throws(()=>calculateScenario({...input,burn:Number.MAX_VALUE,months:2}),/过大/);
assert.throws(()=>calculateScenario({...input,optionPool:1}),/小于/);
assert.throws(()=>calculateScenario({...input,optionPool:.8}),/超过/);
const holders=[{id:'founders',name:'创始团队',percent:70},{id:'old',name:'历史股东',percent:30}];
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} != ${expected}`);
const before=calculateCapTable(holders,{...input,optionPool:.1},'before');
close(before[0].after,42);close(before[1].after,18);close(before[2].after,30);close(before[3].after,10);
close(before.reduce((sum,row)=>sum+row.after,0),100);
const after=calculateCapTable(holders,{...input,optionPool:.1},'after');
close(after[0].after,44.1);close(after[1].after,18.9);close(after[2].after,27);close(after[3].after,10);
close(after.reduce((sum,row)=>sum+row.after,0),100);
assert.throws(()=>calculateCapTable([{id:'x',name:'股东',percent:99}],input),/100%/);
assert.throws(()=>calculateCapTable([{id:'x',name:'',percent:100}],input),/名称/);
assert.throws(()=>calculateCapTable([{id:'x',name:'股东',percent:NaN}],input),/有限数值/);
assert.throws(()=>calculateCapTable(holders,{...input,pre:0,raise:0}),/大于零/);
const context={stage:'early',cashFlow:'negative',strategic:true,research:true,equity:'yes',repayment:'no'};
const diagnosis=diagnoseCapital(context);assert.equal(diagnosis.length,6);
assert.equal(diagnosis.find(item=>item.id==='angel').fit,'可优先研究');
assert.equal(diagnosis.find(item=>item.id==='debt').fit,'当前假设不适配');
assert.equal(diagnosis.find(item=>item.id==='policy').fit,'条件待确认');
assert.ok(diagnoseCapital({...context,equity:'no'}).slice(0,4).every(item=>item.fit==='当前假设不适配'));
assert.ok(diagnoseCapital({...context,stage:'unknown',cashFlow:'unknown',equity:'unknown',repayment:'unknown'}).every(item=>item.fit==='条件待确认'));
assert.equal(diligenceFramework('investor').length,7);assert.equal(diligenceFramework('founder').length,7);
assert.notDeepEqual(diligenceFramework('investor'),diligenceFramework('founder'));
console.log('PASS: financial formulas, zero/invalid/overflow inputs, cap-table conservation, both option-pool assumptions, six capital archetypes and role-specific diligence');
